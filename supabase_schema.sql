-- 1. ตาราง care_centers (ศูนย์ดูแลผู้สูงอายุ / ผู้ป่วย)
CREATE TABLE IF NOT EXISTS public.care_centers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT DEFAULT '',
    province TEXT DEFAULT '',
    lat NUMERIC DEFAULT 0,
    lng NUMERIC DEFAULT 0,
    price NUMERIC DEFAULT 0,
    type TEXT DEFAULT 'both', -- 'daily', 'monthly', 'both'
    rating NUMERIC DEFAULT 5,
    phone TEXT DEFAULT '',
    website TEXT DEFAULT '',
    map_url TEXT DEFAULT '',
    image_urls JSONB DEFAULT '[]'::jsonb,
    description TEXT DEFAULT '',
    services JSONB DEFAULT '[]'::jsonb,
    packages JSONB DEFAULT '[]'::jsonb,
    room_types JSONB DEFAULT '[]'::jsonb,
    has_government_certificate BOOLEAN DEFAULT false,
    brand_name TEXT DEFAULT '',
    brand_logo_url TEXT DEFAULT '',
    is_partner BOOLEAN DEFAULT false,
    status TEXT DEFAULT 'visible', -- 'visible', 'hidden', 'pending'
    utm_source TEXT DEFAULT '',
    utm_medium TEXT DEFAULT '',
    utm_campaign TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_care_centers_status ON public.care_centers (status);
CREATE INDEX IF NOT EXISTS idx_care_centers_province ON public.care_centers (province);

-- 2. ตาราง blogs (บทความ)
CREATE TABLE IF NOT EXISTS public.blogs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    content TEXT DEFAULT '',
    excerpt TEXT DEFAULT '',
    cover_image TEXT DEFAULT '',
    author TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    tags JSONB DEFAULT '[]'::jsonb,
    is_published BOOLEAN DEFAULT true,
    is_recent BOOLEAN DEFAULT false,
    is_featured BOOLEAN DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_blogs_slug ON public.blogs (slug);
CREATE INDEX IF NOT EXISTS idx_blogs_is_published ON public.blogs (is_published);

-- 3. ตาราง consultations (คำขอปรึกษา / นัดหมาย)
CREATE TABLE IF NOT EXISTS public.consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    line_id TEXT DEFAULT '',
    contact_name TEXT DEFAULT '',
    recipient_name TEXT DEFAULT '',
    recipient_age NUMERIC DEFAULT 0,
    relationship_to_recipient TEXT DEFAULT '',
    branch TEXT DEFAULT '',
    budget TEXT DEFAULT '',
    room_type TEXT DEFAULT '',
    convenient_time TEXT DEFAULT '',
    message TEXT DEFAULT '',
    status TEXT DEFAULT 'pending',
    submitted_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_consultations_status ON public.consultations (status);

-- 4. ตาราง contacts (ข้อความติดต่อเรา)
CREATE TABLE IF NOT EXISTS public.contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT DEFAULT '',
    email TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    subject TEXT DEFAULT '',
    message TEXT DEFAULT '',
    status TEXT DEFAULT 'unread',
    submitted_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 5. ตาราง admins (ผู้ดูแลระบบ)
CREATE TABLE IF NOT EXISTS public.admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    email TEXT DEFAULT '',
    full_name TEXT DEFAULT '',
    role TEXT DEFAULT 'admin', -- 'super_admin' or 'admin'
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    last_login TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_admins_username ON public.admins (username);

-- 6. ตาราง ads (โฆษณา / แบนเนอร์)
CREATE TABLE IF NOT EXISTS public.ads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url TEXT NOT NULL,
    link_url TEXT DEFAULT '',
    title TEXT DEFAULT '',
    description TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 7. ตาราง provider_signups (ใบสมัครผู้ให้บริการ)
CREATE TABLE IF NOT EXISTS public.provider_signups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    center_name TEXT DEFAULT '',
    owner_name TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    line_id TEXT DEFAULT '',
    address TEXT DEFAULT '',
    subdistrict TEXT DEFAULT '',
    district TEXT DEFAULT '',
    province TEXT DEFAULT '',
    postal_code TEXT DEFAULT '',
    center_type TEXT DEFAULT '',
    capacity TEXT DEFAULT '',
    services TEXT DEFAULT '',
    description TEXT DEFAULT '',
    status TEXT DEFAULT 'pending'
);

-- 8. ตาราง traffic (บันทึกการเข้าชม / วิเคราะห์ UTM)
CREATE TABLE IF NOT EXISTS public.traffic (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    event_type TEXT DEFAULT 'page_view',
    page_path TEXT DEFAULT '/',
    center_id NUMERIC,
    center_name TEXT DEFAULT '',
    utm_source TEXT DEFAULT '',
    utm_medium TEXT DEFAULT '',
    utm_campaign TEXT DEFAULT '',
    referrer TEXT DEFAULT '',
    user_agent TEXT DEFAULT '',
    ip TEXT DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_traffic_timestamp ON public.traffic (timestamp);

