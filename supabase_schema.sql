-- ==============================================================================
-- 11. Row Level Security (RLS) Configuration
-- ==============================================================================
-- เปิด RLS สำหรับตารางทั้งหมดเพื่อความปลอดภัยสูงสุด
ALTER TABLE public.care_centers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.blogs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consultations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.provider_signups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.traffic ENABLE ROW LEVEL SECURITY;

-- นโยบาย Public Read สำหรับข้อมูลที่แสดงหน้าเว็บ
CREATE POLICY "Public Read care_centers" ON public.care_centers FOR SELECT USING (true);
CREATE POLICY "Public Read blogs" ON public.blogs FOR SELECT USING (true);
CREATE POLICY "Public Read ads" ON public.ads FOR SELECT USING (true);

-- นโยบาย Public Insert สำหรับฟอร์มหน้าเว็บที่ผู้ใช้กรอกเข้ามา
CREATE POLICY "Public Insert consultations" ON public.consultations FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Insert contacts" ON public.contacts FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Insert provider_signups" ON public.provider_signups FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Insert traffic" ON public.traffic FOR INSERT WITH CHECK (true);

