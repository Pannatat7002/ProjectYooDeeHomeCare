-- 9. Setup Storage Bucket for Images (yoodee-images)
-- ==============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('yoodee-images', 'yoodee-images', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- นโยบายเปิดให้ทุกคนอ่านรูปภาพใน bucket ได้โดยตรง (Public Read)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' AND policyname = 'Public Access for yoodee-images'
    ) THEN
        CREATE POLICY "Public Access for yoodee-images"
        ON storage.objects FOR SELECT
        USING ( bucket_id = 'yoodee-images' );
    END IF;
END $$;

-- นโยบายอนุญาตให้อัปโหลดรูปภาพลง bucket ได้
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' AND policyname = 'Allow Uploads for yoodee-images'
    ) THEN
        CREATE POLICY "Allow Uploads for yoodee-images"
        ON storage.objects FOR INSERT
        WITH CHECK ( bucket_id = 'yoodee-images' );
    END IF;
END $$;

-- นโยบายอนุญาตให้ลบหรือแก้ไขรูปภาพใน bucket ได้
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' AND policyname = 'Allow Delete for yoodee-images'
    ) THEN
        CREATE POLICY "Allow Delete for yoodee-images"
        ON storage.objects FOR DELETE
        USING ( bucket_id = 'yoodee-images' );
    END IF;
END $$;

